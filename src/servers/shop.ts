import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { DATA } from "../config";

/**
 * One entry of GET /shop/get -> items[]. Field names are the ones the client's
 * shop code reads (see docs/SHOP.md).
 */
export interface ShopItem {
  itemId: string;
  shopCategory: 0 | 1 | 2; // 0 skins, 1 features/animals, 2 deals
  itemType: 0 | 1 | 2 | 3; // 0 skin, 1 animal unlock, 2 deal bundle, 3 powerup
  animalType?: number;
  animalSpecies?: number;
  animalSubSpecies?: number;
  season?: number;
  currencyType: 0 | 1; // 0 coins, 1 gems
  price: number;
  info?: string;
  promotions?: string;
}

const catalogPath = join(DATA, "shop-catalog.json");

let cached: ShopItem[] | null = null;

/** Catalog generated by `bun mopeio.ts shop` (introspects the real client). */
export function shopCatalog(): ShopItem[] {
  if (cached) return cached;
  if (existsSync(catalogPath)) {
    cached = JSON.parse(readFileSync(catalogPath, "utf8")) as ShopItem[];
  } else {
    console.warn("[shop] data/shop-catalog.json missing – run `bun mopeio.ts probe`; using a tiny fallback catalog");
    cached = [
      { itemId: "mouse_1", shopCategory: 0, itemType: 0, animalType: 1, animalSpecies: 111, animalSubSpecies: 0, season: 1, currencyType: 0, price: 500 },
    ];
  }
  return cached;
}

export function reloadCatalog() {
  cached = null;
  return shopCatalog();
}
